from collections import defaultdict
from itertools import combinations

def read_input(file_path):
    schema = defaultdict(list)
    fds = defaultdict(list)
    with open(file_path, 'r') as file:
        lines = file.readlines()

        reading_tables = True
        for line in lines:
            line = line.strip()
            if not line:
                continue
            if line.startswith("# Các phụ thuộc hàm"):
                reading_tables = False
            elif reading_tables:
                if ":" in line:
                    table_name, attributes = line.split(":")
                    attributes = attributes.strip()[1:-1].split(", ")
                    schema[table_name.strip()] = set(attributes)
            else:
                if ":" in line:
                    table_name, dependencies = line.split(":")
                    dependencies = dependencies.strip()[1:-1].split(", ")
                    for dep in dependencies:
                        if "->" in dep:
                            try:
                                lhs, rhs = dep.split(" -> ")
                                if lhs and rhs:
                                    fds[table_name.strip()].append((lhs.strip(), rhs.strip()))
                                else:
                                    print(f"Phụ thuộc hàm không hợp lệ: {dep}")
                            except ValueError:
                                print(f"Lỗi phân tích phụ thuộc hàm: {dep}")
                        else:
                            if "PRIMARY KEY" in dep or "UNIQUE" in dep or "FOREIGN KEY" in dep:
                                continue
                            else:
                                print(f"Phụ thuộc hàm không hợp lệ: {dep}")
    return schema, fds

def calculate_closure(attributes, fds, table):
    closure = set(attributes)
    while True:
        new_closure = closure.copy()
        for lhs, rhs in fds[table]:
            if set(lhs.split(", ")) <= closure:
                new_closure.update(rhs.split(", "))
        if new_closure == closure:
            break
        closure = new_closure
    return closure

def find_keys(table, schema, fds):
    all_attributes = schema[table]
    minimal_keys = []
    for i in range(1, len(all_attributes) + 1):
        for subset in combinations(all_attributes, i):
            closure = calculate_closure(subset, fds, table)
            if closure == all_attributes:
                is_minimal = True
                for key in minimal_keys:
                    if set(key).issubset(subset):
                        is_minimal = False
                        break
                if is_minimal:
                    minimal_keys.append(subset)
    return minimal_keys

def write_output(file_path, schema, fds):
    with open(file_path, 'w') as file:
        for table in schema.keys():
            file.write(f"Khóa của bảng {table}:\n")
            keys = find_keys(table, schema, fds)
            for key in keys:
                file.write(f"  {key}\n")

